char	*ft_strrchr(const char *s, int c)
{
	const char	*ptr;

	ptr = 0;
	while (*s != '\0')
	{
		if (*s == c)
			ptr = s;
	}
	if (c == '\0')
		ptr = s;
	return (ptr);
}
